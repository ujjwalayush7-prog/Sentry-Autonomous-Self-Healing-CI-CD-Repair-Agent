"""
Patch Application Engine
Robustly applies unified diffs generated by LLMs to source files.
Features dual strategy:
1. Git apply / patch standard tool
2. Intelligent Python-based hunk applier with whitespace and line-offset tolerance
"""

import os
import re
import subprocess
import logging
from typing import Tuple, Optional

logger = logging.getLogger(__name__)


def apply_patch(repo_path: str, target_file: str, unified_diff: str) -> Tuple[bool, str]:
    """
    Applies a unified diff to a target file in repo_path.

    Args:
        repo_path: Root directory of the repository
        target_file: Relative path to the file to modify
        unified_diff: Unified diff string (starts with --- or diff --git)

    Returns:
        (success: bool, message: str)
    """
    abs_repo = os.path.abspath(repo_path)
    # Normalize target file path
    target_rel = target_file.replace("\\", "/").lstrip("/")
    abs_target = os.path.join(abs_repo, target_rel.replace("/", os.sep))

    if not os.path.exists(abs_target):
        # Search for file basename if full path didn't match
        basename = os.path.basename(target_rel)
        found = False
        for root, _, files in os.walk(abs_repo):
            if basename in files and not any(p in root for p in [".git", "node_modules"]):
                abs_target = os.path.join(root, basename)
                target_rel = os.path.relpath(abs_target, abs_repo).replace(os.sep, "/")
                found = True
                break
        if not found:
            return False, f"Target file not found in repository: {target_file}"

    # Strategy 1: Try applying via python hunk replacer directly on file contents
    success, msg = apply_hunks_directly(abs_target, unified_diff)
    if success:
        return True, f"Successfully applied patch to {target_rel} (direct hunk engine)"

    # Strategy 2: Try git apply with relaxed whitespace
    try:
        # Write diff to temporary file
        diff_file = os.path.join(abs_repo, ".sentry_temp.patch")
        # Ensure diff headers reference the correct relative path
        normalized_diff = ensure_diff_headers(unified_diff, target_rel)
        with open(diff_file, "w", encoding="utf-8") as f:
            f.write(normalized_diff)

        res = subprocess.run(
            ["git", "apply", "--ignore-whitespace", "--unidiff-zero", ".sentry_temp.patch"],
            cwd=abs_repo,
            capture_output=True,
            text=True,
            timeout=10,
        )
        if os.path.exists(diff_file):
            os.remove(diff_file)

        if res.returncode == 0:
            return True, f"Successfully applied patch to {target_rel} (git apply)"
        else:
            logger.warning(f"git apply failed: {res.stderr}")
    except Exception as e:
        logger.warning(f"git apply exception: {e}")

    # Strategy 3: Try fuzzy search/replace on removed/added lines
    success, msg = apply_fuzzy_replacement(abs_target, unified_diff)
    if success:
        return True, f"Successfully applied patch to {target_rel} (fuzzy replacement engine)"

    return False, f"All patch application strategies failed for {target_rel}. Details: {msg}"


def ensure_diff_headers(diff: str, target_rel: str) -> str:
    """Ensures diff has valid a/ and b/ headers for git apply."""
    lines = diff.splitlines()
    has_a = any(l.startswith("--- ") for l in lines)
    has_b = any(l.startswith("+++ ") for l in lines)

    if not has_a or not has_b:
        header = f"--- a/{target_rel}\n+++ b/{target_rel}\n"
        return header + diff
    return diff


def apply_hunks_directly(file_path: str, diff_text: str) -> Tuple[bool, str]:
    """
    Parses unified diff hunks and applies them to file contents,
    handling line offsets, interspersed context lines, and leading spaces gracefully.
    """
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            initial_content = f.read()

        original_content = initial_content
        diff_lines = diff_text.splitlines()

        # Extract hunks (starts with @@ ... @@)
        hunk_indices = [i for i, l in enumerate(diff_lines) if l.startswith("@@")]
        if not hunk_indices:
            return False, "No @@ hunk headers found in diff"

        for h_idx in hunk_indices:
            end_idx = len(diff_lines)
            for next_idx in hunk_indices:
                if next_idx > h_idx:
                    end_idx = next_idx
                    break

            hunk_body = diff_lines[h_idx + 1:end_idx]
            old_hunk_lines = []
            new_hunk_lines = []
            removed_only = []
            added_only = []

            for hl in hunk_body:
                if hl.startswith("---") or hl.startswith("+++") or hl.startswith("\\"):
                    continue
                if hl.startswith("-"):
                    old_hunk_lines.append(hl[1:])
                    removed_only.append(hl[1:])
                elif hl.startswith("+"):
                    new_hunk_lines.append(hl[1:])
                    added_only.append(hl[1:])
                elif hl.startswith(" ") or hl == "":
                    content = hl[1:] if hl.startswith(" ") else hl
                    old_hunk_lines.append(content)
                    new_hunk_lines.append(content)

            # 1. Try matching full hunk sequence (including context lines)
            if old_hunk_lines:
                file_lines = original_content.splitlines()
                stripped_old = [l.strip() for l in old_hunk_lines]
                match_start = -1
                for i in range(len(file_lines) - len(stripped_old) + 1):
                    window = [file_lines[i + k].strip() for k in range(len(stripped_old))]
                    if window == stripped_old:
                        match_start = i
                        break

                if match_start != -1:
                    new_file_lines = (
                        file_lines[:match_start] +
                        new_hunk_lines +
                        file_lines[match_start + len(stripped_old):]
                    )
                    original_content = "\n".join(new_file_lines) + "\n"
                    continue

            # 2. Fallback: Try contiguous removed-only matching
            stripped_removed = [l.strip() for l in removed_only if l.strip()]
            if stripped_removed:
                file_lines = original_content.splitlines()
                match_start = -1
                for i in range(len(file_lines) - len(stripped_removed) + 1):
                    window = [file_lines[i + k].strip() for k in range(len(stripped_removed))]
                    if window == stripped_removed:
                        match_start = i
                        break

                if match_start != -1:
                    new_file_lines = (
                        file_lines[:match_start] +
                        added_only +
                        file_lines[match_start + len(stripped_removed):]
                    )
                    original_content = "\n".join(new_file_lines) + "\n"
                    continue

        if original_content == initial_content:
            return False, "Hunk matching did not modify file contents"

        # Write modified content back
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(original_content)

        return True, "Hunk applied"
    except Exception as e:
        return False, f"Direct hunk error: {e}"


def apply_fuzzy_replacement(file_path: str, diff_text: str) -> Tuple[bool, str]:
    """
    Fallback: extracts all '-' and '+' lines from diff, and attempts
    a whitespace-insensitive line replacement.
    """
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            content = f.read()

        diff_lines = diff_text.splitlines()
        del_lines = [l[1:].strip() for l in diff_lines if l.startswith("-") and not l.startswith("---")]
        add_lines = [l[1:] for l in diff_lines if l.startswith("+") and not l.startswith("+++")]

        if not del_lines or not add_lines:
            return False, "Could not extract added/removed lines"

        lines = content.splitlines()
        first_del = del_lines[0]

        # Find first matching line
        match_idx = -1
        for idx, line in enumerate(lines):
            if line.strip() == first_del:
                match_idx = idx
                break

        if match_idx == -1:
            return False, f"Could not find matching target line: '{first_del}'"

        # Replace deleted slice with added lines
        del_count = len(del_lines)
        new_lines = lines[:match_idx] + add_lines + lines[match_idx + del_count:]
        new_content = "\n".join(new_lines)
        if not new_content.endswith("\n"):
            new_content += "\n"

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(new_content)

        return True, "Fuzzy replacement applied"
    except Exception as e:
        return False, f"Fuzzy replacement error: {e}"
